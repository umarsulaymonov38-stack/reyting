-- 6. Server funksiyasi uchun (faqat service_role): navbatdan olish, natijani yozish, Eskiz kaliti
create or replace function public.sms_claim(p_limit int default 60) returns setof public.sms_queue
language plpgsql security definer set search_path = public as $$
declare t date := (now() at time zone 'Asia/Tashkent')::date;
begin
  -- kechagi Keldi/Ketdi SMS'lari endi yuborilmaydi
  update public.sms_queue set status = 'xato', error = 'eskirgan (kun o''tib ketdi)'
   where status in ('navbat', 'yuborilmoqda') and kind in ('keldi', 'ketdi') and day < t;
  return query
  update public.sms_queue q set status = 'yuborilmoqda', tries = q.tries + 1, claimed_at = now()
   where q.id in (select x.id from public.sms_queue x
                   where (x.status = 'navbat' or (x.status = 'yuborilmoqda' and x.claimed_at < now() - interval '10 minutes'))
                     and x.tries < 3
                   order by x.id limit p_limit for update skip locked)
  returning q.*;
end $$;
create or replace function public.sms_done(p_id bigint, p_ok boolean, p_provider text, p_error text) returns void
language sql security definer set search_path = public as $$
  update public.sms_queue set status = case when p_ok then 'yuborildi' when tries >= 3 then 'xato' else 'navbat' end,
         sent_at = case when p_ok then now() end, provider_id = nullif(p_provider, ''), error = p_error
   where id = p_id
$$;
create or replace function public.sms_token_get() returns public.sms_secret language sql security definer set search_path = public as $$
  select * from public.sms_secret where id = 1
$$;
create or replace function public.sms_token_set(p_token text) returns void language sql security definer set search_path = public as $$
  insert into public.sms_secret (id, token, token_at) values (1, p_token, now())
  on conflict (id) do update set token = excluded.token, token_at = now()
$$;
revoke all on function public.sms_claim(int) from public, anon, authenticated;
revoke all on function public.sms_done(bigint, boolean, text, text) from public, anon, authenticated;
revoke all on function public.sms_token_get() from public, anon, authenticated;
revoke all on function public.sms_token_set(text) from public, anon, authenticated;
grant execute on function public.sms_claim(int) to service_role;
grant execute on function public.sms_done(bigint, boolean, text, text) to service_role;
grant execute on function public.sms_token_get() to service_role;
grant execute on function public.sms_token_set(text) to service_role;

-- 7. Jadval: har daqiqada navbatni yuborish, har kuni 10:00 da (Toshkent) to'lov eslatmasi
create or replace function public.yk_sms_kick() returns void
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from public.sms_queue where status = 'navbat') then
    perform net.http_post(
      url := 'https://yzaxyjypswpjcebmjsnj.supabase.co/functions/v1/sms-yubor',
      body := '{}'::jsonb,
      headers := '{"Content-Type": "application/json"}'::jsonb,
      timeout_milliseconds := 60000);
  end if;
end $$;
revoke all on function public.yk_sms_kick() from public, anon, authenticated;

