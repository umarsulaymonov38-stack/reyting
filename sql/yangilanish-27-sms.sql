-- Qachon SMS ketadi (har biri admin tomonidan alohida yoqiladi — boshida hammasi O'CHIQ):
--  1) Keldi:  o'quvchi kunning birinchi marta turniketdan o'tganida (kuniga bir marta).
--  2) Ketdi:  16:45 dan keyin turniketdan birinchi marta o'tganida (kuniga bir marta).
--  3) To'lov: oyning 5-sanasigacha to'lanmagan bo'lsa — 6, 11, 16, 21, 26, 31-sanalarda (har 5 kunda) soat 10:00 da.
-- SMS faqat ota-ona telefoni kiritilgan, turniket hisoblaydigan (3–10-sinf) o'quvchilarga ketadi.
-- SMSlar navbatga yoziladi va har daqiqada "sms-yubor" server funksiyasi orqali Eskiz'ga yuboriladi.

create extension if not exists pg_net;
create extension if not exists pg_cron;

-- 1. Sozlamalar (admin o'zgartiradi)
create table if not exists public.sms_config (
  id int primary key default 1 check (id = 1),
  on_keldi boolean not null default false,
  on_ketdi boolean not null default false,
  on_tolov boolean not null default false,
  tpl_keldi text not null default 'Hurmatli ota-ona! Farzandingiz {ism} bugun soat {vaqt} da maktabga keldi. Samarqand Yuksalish maktabi',
  tpl_ketdi text not null default 'Hurmatli ota-ona! Farzandingiz {ism} soat {vaqt} da maktabdan chiqdi. Samarqand Yuksalish maktabi',
  tpl_tolov text not null default 'Hurmatli ota-ona! {ism} uchun {oy} oyi to''lovi {kun} kun kechikmoqda. Iltimos, to''lovni amalga oshiring. Samarqand Yuksalish maktabi',
  ketdi_from time not null default '16:45',
  tolov_due int not null default 5,
  tolov_every int not null default 5,
  updated_at timestamptz not null default now()
);
insert into public.sms_config (id) values (1) on conflict (id) do nothing;
alter table public.sms_config enable row level security;
grant select, update on public.sms_config to authenticated;
drop policy if exists sms_config_admin on public.sms_config;
create policy sms_config_admin on public.sms_config for all to authenticated
  using (public.yk_role() = 'admin') with check (public.yk_role() = 'admin');

-- Eskiz kirish kaliti (token) — faqat server funksiyasi o'qiydi
create table if not exists public.sms_secret (id int primary key default 1 check (id = 1), token text, token_at timestamptz);
alter table public.sms_secret enable row level security;
revoke all on public.sms_secret from anon, authenticated;

-- 2. SMS navbati va jurnali
create table if not exists public.sms_queue (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('keldi', 'ketdi', 'tolov', 'test')),
  student_id text,
  phone text not null,
  text text not null,
  day date not null default (now() at time zone 'Asia/Tashkent')::date,
  status text not null default 'navbat' check (status in ('navbat', 'yuborilmoqda', 'yuborildi', 'xato')),
  tries int not null default 0,
  error text,
  provider_id text,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  unique (kind, student_id, day)
);
create index if not exists sms_queue_status_idx on public.sms_queue (status, id);
create index if not exists sms_queue_day_idx on public.sms_queue (day desc, kind);
alter table public.sms_queue enable row level security;
grant select on public.sms_queue to authenticated;
drop policy if exists sms_queue_admin on public.sms_queue;
create policy sms_queue_admin on public.sms_queue for select to authenticated using (public.yk_role() = 'admin');

-- 3. Yordamchilar
create or replace function public.yk_phone_norm(p text) returns text language sql immutable as $$
  select case when length(d) = 9 then '998' || d when length(d) = 12 and d like '998%' then d end
    from (select regexp_replace(coalesce(p, ''), '\D', '', 'g') d) x
$$;
-- SMS uchun ism: familiya va ism (otasining ismisiz), tutuq belgilari oddiy ' ko'rinishida (SMS qisqa bo'lishi uchun)
create or replace function public.yk_sms_name(p text) returns text language sql immutable as $$
  select array_to_string((regexp_split_to_array(btrim(translate(coalesce(p, ''), 'ʻʼ’‘`', '''''''''''')), '\s+'))[1:2], ' ')
$$;

-- Keldi / Ketdi SMS'ini navbatga qo'yish (kuniga bir marta)
create or replace function public.yk_sms_add(p_kind text, p_sid text, p_ts timestamptz) returns void
language plpgsql security definer set search_path = public as $$
declare c public.sms_config; ph text; nm text; tx text;
begin
  select * into c from public.sms_config where id = 1;
  if c.id is null or not (case p_kind when 'keldi' then c.on_keldi when 'ketdi' then c.on_ketdi else false end) then return; end if;
  select public.yk_phone_norm(sp.parent_phone), s.full_name into ph, nm
    from public.students s join public.student_private sp on sp.student_id = s.id where s.id::text = p_sid;
  if ph is null then return; end if;
  tx := replace(replace(case p_kind when 'keldi' then c.tpl_keldi else c.tpl_ketdi end,
          '{ism}', public.yk_sms_name(nm)), '{vaqt}', to_char(p_ts at time zone 'Asia/Tashkent', 'HH24:MI'));
  insert into public.sms_queue (kind, student_id, phone, text, day)
  values (p_kind, p_sid, ph, tx, (p_ts at time zone 'Asia/Tashkent')::date)
  on conflict (kind, student_id, day) do nothing;
end $$;
revoke all on function public.yk_sms_add(text, text, timestamptz) from public, anon, authenticated;

-- 4. Turniket: davomat (yangilanish-24 qoidalari) + Keldi/Ketdi SMS
create or replace function public.tk_push(p_token text, p_events jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare e record; sid public.students.id%type; cid bigint; eid bigint; lt timestamp; n int := 0;
        kf time := coalesce((select ketdi_from from public.sms_config where id = 1), time '16:45');
begin
  if not exists (select 1 from public.tk_config where token = p_token) then
    raise exception 'Kalit noto''g''ri' using errcode = '28000';
  end if;
  for e in select * from jsonb_to_recordset(p_events) as x(emp text, ts timestamptz, door text) loop
    continue when coalesce(e.emp, '') = '' or e.ts is null;
    select s.id, s.class_id into sid, cid from public.students s join public.classes c on c.id = s.class_id
     where s.ext_id = e.emp and c.kind is distinct from 'rep' and coalesce(c.grp, '') = '' limit 1;
    insert into public.turnstile_events (emp_no, student_id, ts, door)
    values (e.emp, sid::text, e.ts, coalesce(e.door, '')) on conflict do nothing returning id into eid;
    if eid is not null and sid is not null and public.yk_tk_class(cid) then
      lt := e.ts at time zone 'Asia/Tashkent';
      if lt::time <= time '09:30' then
        insert into public.daily_scores (student_id, day, att, excused, arrived_at) values (sid, lt::date, 1, false, e.ts)
        on conflict (student_id, day) do update
          set att = 1, excused = false, arrived_at = least(coalesce(public.daily_scores.arrived_at, excluded.arrived_at), excluded.arrived_at);
        n := n + 1;
      elsif lt::time >= time '16:40' then
        insert into public.daily_scores (student_id, day, left_at) values (sid, lt::date, e.ts)
        on conflict (student_id, day) do update
          set left_at = greatest(coalesce(public.daily_scores.left_at, excluded.left_at), excluded.left_at);
        n := n + 1;
      end if;
      -- SMS faqat yangi o'tishlar uchun (ko'prik eski kunlarni keyin yuborsa — SMS ketmaydi)
      if e.ts > now() - interval '3 hours' then
        perform public.yk_sms_add(case when lt::time < kf then 'keldi' else 'ketdi' end, sid::text, e.ts);
      end if;
    end if;
    sid := null; cid := null; eid := null;
  end loop;
  return n;
end $$;
revoke all on function public.tk_push(text, jsonb) from public;
grant execute on function public.tk_push(text, jsonb) to anon, authenticated;

-- 5. To'lov eslatmasi: joriy oy to'lanmagan bo'lsa (asosiy sinflar, iyun–avgust ta'til — yuborilmaydi)
create or replace function public.yk_sms_tolov(p_force boolean default false, p_class bigint default null) returns int
language plpgsql security definer set search_path = public as $$
declare c public.sms_config; t date := (now() at time zone 'Asia/Tashkent')::date; m date := date_trunc('month', t)::date;
        late int; n int;
        oy text[] := array['Yanvar','Fevral','Mart','Aprel','May','Iyun','Iyul','Avgust','Sentyabr','Oktyabr','Noyabr','Dekabr'];
begin
  select * into c from public.sms_config where id = 1;
  late := extract(day from t)::int - c.tolov_due;
  if extract(month from t) in (6, 7, 8) then return 0; end if;
  if not p_force then
    if not c.on_tolov or late < 1 or (late - 1) % greatest(c.tolov_every, 1) <> 0 then return 0; end if;
  elsif late < 1 then
    raise exception 'To''lov muddati (har oyning %-sanasi) hali o''tmagan', c.tolov_due;
  end if;
  insert into public.sms_queue (kind, student_id, phone, text, day)
  select 'tolov', s.id::text, public.yk_phone_norm(sp.parent_phone),
         replace(replace(replace(c.tpl_tolov, '{ism}', public.yk_sms_name(s.full_name)), '{oy}', oy[extract(month from t)::int]), '{kun}', late::text), t
    from public.students s
    join public.classes cl on cl.id = s.class_id
    join public.student_private sp on sp.student_id = s.id
   where cl.kind is distinct from 'rep' and coalesce(cl.grp, '') = '' and coalesce(cl.subject, '') !~* '^(arab|koreys)'
     and coalesce(btrim(s.full_name), '') <> '' and public.yk_phone_norm(sp.parent_phone) is not null
     and (p_class is null or s.class_id = p_class)
     and not exists (select 1 from public.payments p where p.student_id = s.id and p.month = m and p.paid)
  on conflict (kind, student_id, day) do nothing;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.yk_sms_tolov(boolean, bigint) from public, anon, authenticated;

