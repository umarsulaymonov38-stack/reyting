-- Yangilanish 5: Hikvision turniketlari bilan bog'lash (avtomatik davomat).
-- Supabase → SQL Editor ga to'liq nusxalab, "Run" bosing. Qayta ishga tushirish xavfsiz.
-- Oxirida ko'prik dastur uchun MAXFIY KALIT (token) chiqadi — uni turniket/config.json fayliga yozasiz.

-- 1. O'quvchining turniketdagi ID raqami (Hikvision: "Employee No.") va kelgan vaqti
alter table public.students add column if not exists ext_id text;
create unique index if not exists students_ext_id_uq on public.students (ext_id) where coalesce(ext_id, '') <> '';
alter table public.daily_scores add column if not exists arrived_at timestamptz;

-- 2. Ko'prik dastur kaliti (API orqali o'qib bo'lmaydi)
create table if not exists public.tk_config (
  id int primary key default 1 check (id = 1),
  token text not null,
  updated_at timestamptz not null default now()
);
alter table public.tk_config enable row level security;
revoke all on public.tk_config from anon, authenticated;
insert into public.tk_config (id, token)
values (1, md5(random()::text || clock_timestamp()::text) || md5(random()::text))
on conflict (id) do nothing;

-- 3. Turniket voqealari jurnali (admin ko'radi)
create table if not exists public.turnstile_events (
  id bigint generated by default as identity primary key,
  emp_no text not null,
  student_id bigint,
  ts timestamptz not null,
  door text not null default '',
  created_at timestamptz not null default now(),
  unique (emp_no, ts, door)
);
create index if not exists turnstile_events_ts_idx on public.turnstile_events (ts desc);
alter table public.turnstile_events enable row level security;
grant select on public.turnstile_events to authenticated;
drop policy if exists tk_read on public.turnstile_events;
create policy tk_read on public.turnstile_events for select to authenticated using (public.yk_role() = 'admin');

-- Ismlarni solishtirish uchun: kichik harf, belgilarsiz, so'zlar tartiblangan ("Valiyev Ali" = "Ali Valiyev")
create or replace function public.yk_norm(t text) returns text language sql immutable as $$
  select array_to_string(array(
    select w from unnest(string_to_array(regexp_replace(lower(coalesce(t, '')), '[^[:alnum:] ]', '', 'g'), ' ')) w
     where w <> '' order by w), ' ')
$$;

-- 4. Ko'prik dastur voqealarni yuboradi: [{ "emp": "123", "ts": "2026-10-21T08:01:02+05:00", "door": "1-eshik" }, ...]
--    Tanilgan o'quvchiga o'sha kuni davomat "keldi" (1) qo'yiladi, birinchi o'tgan vaqti yoziladi.
--    Faqat asosiy sinf (1–10-sinflar) davomati belgilanadi; guruh darslari davomatini o'qituvchi qo'yadi.
create or replace function public.tk_push(p_token text, p_events jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare e record; sid bigint; eid bigint; d date; n int := 0;
begin
  if not exists (select 1 from public.tk_config where token = p_token) then
    raise exception 'Kalit noto''g''ri' using errcode = '28000';
  end if;
  for e in select * from jsonb_to_recordset(p_events) as x(emp text, ts timestamptz, door text) loop
    continue when coalesce(e.emp, '') = '' or e.ts is null;
    select s.id into sid from public.students s join public.classes c on c.id = s.class_id
     where s.ext_id = e.emp and c.kind is distinct from 'rep' and coalesce(c.grp, '') = '' limit 1;
    insert into public.turnstile_events (emp_no, student_id, ts, door)
    values (e.emp, sid, e.ts, coalesce(e.door, '')) on conflict do nothing returning id into eid;
    if eid is not null and sid is not null then
      d := (e.ts at time zone 'Asia/Tashkent')::date;
      insert into public.daily_scores (student_id, day, att, arrived_at) values (sid, d, 1, e.ts)
      on conflict (student_id, day) do update
        set att = 1, arrived_at = least(coalesce(public.daily_scores.arrived_at, excluded.arrived_at), excluded.arrived_at);
      n := n + 1;
    end if;
    sid := null; eid := null;
  end loop;
  return n;
end $$;
revoke all on function public.tk_push(text, jsonb) from public;
grant execute on function public.tk_push(text, jsonb) to anon, authenticated;

-- 5. Turniketdagi ro'yxatni o'quvchilar bilan avtomatik bog'lash (ism-familiya bo'yicha).
--    [{ "emp": "123", "name": "Valiyev Ali" }, ...] → bog'langanlar soni va bog'lanmaganlar ro'yxati.
--    Allaqachon ID yozilgan o'quvchiga tegilmaydi; bir xil ismli bir nechta o'quvchi bo'lsa — qo'lda bog'lanadi.
create or replace function public.tk_map(p_token text, p_people jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare p record; sid bigint; cnt int; linked int := 0; already int := 0; miss jsonb := '[]'::jsonb;
begin
  if not exists (select 1 from public.tk_config where token = p_token) then
    raise exception 'Kalit noto''g''ri' using errcode = '28000';
  end if;
  for p in select * from jsonb_to_recordset(p_people) as x(emp text, name text) loop
    continue when coalesce(p.emp, '') = '';
    if exists (select 1 from public.students where ext_id = p.emp) then already := already + 1; continue; end if;
    select count(*), min(s.id) into cnt, sid from public.students s join public.classes c on c.id = s.class_id
     where c.kind is distinct from 'rep' and coalesce(c.grp, '') = '' and coalesce(s.ext_id, '') = ''
       and public.yk_norm(s.full_name) = public.yk_norm(p.name) and public.yk_norm(p.name) <> '';
    if cnt = 1 then
      update public.students set ext_id = p.emp where id = sid; linked := linked + 1;
    else
      miss := miss || jsonb_build_object('emp', p.emp, 'name', p.name, 'sabab', case when cnt = 0 then 'topilmadi' else 'bir xil ism ' || cnt || ' ta' end);
    end if;
  end loop;
  return jsonb_build_object('boglandi', linked, 'oldin_boglangan', already, 'boglanmadi', miss);
end $$;
revoke all on function public.tk_map(text, jsonb) from public;
grant execute on function public.tk_map(text, jsonb) to anon, authenticated;

notify pgrst, 'reload schema';

