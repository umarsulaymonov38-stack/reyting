-- Yangilanish 56: ota-ona → fan o'qituvchisi: «Nima sababdan farzandimni baholamadingiz?»
--  Ota-ona «Fanlar bo'yicha baholar» jadvalida baho qo'yilmagan dars yonidagi tugmani bosadi —
--  o'qituvchiga xabar boradi (platformada va, yoqilgan bo'lsa, telefon bildirishnomasi).
--  O'qituvchi javob yozadi — javob ota-onaga ko'rinadi va bildirishnoma bilan boradi.
--  Bir dars (o'quvchi + kun + o'qituvchi) uchun bitta savol; so'nggi 14 kun ichidagi darslar uchun.
-- Supabase → SQL Editor ga to'liq nusxalab, "Run" bosing. Qayta ishga tushirish xavfsiz.

do $$
declare t text;
begin
  select format_type(a.atttypid, a.atttypmod) into t from pg_attribute a
   where a.attrelid = 'public.students'::regclass and a.attname = 'id';
  execute format($f$
    create table if not exists public.grade_asks (
      id bigint generated by default as identity primary key,
      ss_id bigint not null references public.subject_scores(id) on delete cascade,
      student_id %s not null references public.students(id) on delete cascade,
      day date not null,
      subject text,
      teacher_id uuid not null,
      parent uuid not null default auth.uid(),
      created_at timestamptz not null default now(),
      answer text,
      answered_at timestamptz,
      unique (ss_id))$f$, t);
end $$;
alter table public.grade_asks enable row level security;
revoke all on public.grade_asks from anon, authenticated;
create index if not exists grade_asks_teacher_idx on public.grade_asks (teacher_id, answered_at);

-- Bildirishnoma turlari: savol (o'qituvchiga), javob (ota-onaga)
alter table public.push_queue drop constraint if exists push_queue_kind_check;
alter table public.push_queue add constraint push_queue_kind_check
  check (kind in ('keldi', 'ketdi', 'kelmadi', 'test', 'yomon', 'yaxshi', 'savol', 'javob'));

-- Ota-ona: fan baholari + dars belgisi (ss_id) — savol yuborish uchun
drop function if exists public.parent_subjects(date, date);
create function public.parent_subjects(p_from date, p_to date)
returns table (student_id text, day date, subject text, att int, excused boolean, hw int, activity int, grade int, ss_id bigint)
language sql stable security definer set search_path = public as $$
  select ss.student_id::text, ss.day, coalesce(nullif(ss.subject, ''), p.full_name, 'Fan'),
         ss.att, ss.excused, ss.hw, ss.activity, ss.grade, ss.id
    from public.subject_scores ss
    join public.my_kids() k on k.id = ss.student_id
    left join public.profiles p on p.id = ss.teacher_id
   where ss.day between p_from and p_to
   order by ss.day desc, 3
$$;
revoke all on function public.parent_subjects(date, date) from public, anon;
grant execute on function public.parent_subjects(date, date) to authenticated;

-- Ota-ona savol yuboradi
create or replace function public.parent_ask_grade(p_ss bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r public.subject_scores; nm text; subj text;
begin
  if public.yk_role() is distinct from 'parent' then raise exception 'Faqat ota-ona' using errcode = '42501'; end if;
  select * into r from public.subject_scores where id = p_ss;
  if r.id is null or not public.yk_is_my_kid(r.student_id::text) then raise exception 'Dars topilmadi' using errcode = '42501'; end if;
  if r.grade is not null then raise exception 'Bu darsda baho qo''yilgan'; end if;
  if r.att = 0 then raise exception 'Farzandingiz bu darsda bo''lmagan'; end if;
  if r.day < (now() at time zone 'Asia/Tashkent')::date - 14 then raise exception 'Faqat so''nggi 14 kundagi darslar uchun'; end if;
  insert into public.grade_asks (ss_id, student_id, day, subject, teacher_id)
  values (r.id, r.student_id, r.day, nullif(r.subject, ''), r.teacher_id)
  on conflict (ss_id) do nothing;
  if not found then raise exception 'Bu dars bo''yicha savol allaqachon yuborilgan'; end if;
  select array_to_string((regexp_split_to_array(btrim(s.full_name), '\s+'))[1:2], ' ') into nm from public.students s where s.id = r.student_id;
  subj := coalesce(nullif(r.subject, ''), 'dars');
  insert into public.push_queue (user_id, kind, student_id, title, body)
  select r.teacher_id, 'savol', r.id::text, '❓ Ota-onadan savol',
         nm || ' (' || subj || ', ' || to_char(r.day, 'DD.MM') || '): nima sababdan farzandimni baholamadingiz?'
   where exists (select 1 from public.push_subs x where x.user_id = r.teacher_id)
  on conflict do nothing;
end $$;
revoke all on function public.parent_ask_grade(bigint) from public, anon;
grant execute on function public.parent_ask_grade(bigint) to authenticated;

-- Ota-ona: yuborgan savollari va javoblar
create or replace function public.parent_asks(p_from date, p_to date)
returns table (ss_id bigint, created_at timestamptz, answer text, answered_at timestamptz)
language sql stable security definer set search_path = public as $$
  select a.ss_id, a.created_at, a.answer, a.answered_at
    from public.grade_asks a join public.my_kids() k on k.id = a.student_id
   where a.day between p_from and p_to
$$;
revoke all on function public.parent_asks(date, date) from public, anon;
grant execute on function public.parent_asks(date, date) to authenticated;

-- O'qituvchi: unga kelgan savollar (javobsizlari va so'nggi 7 kunda javob berilganlari)
create or replace function public.teacher_asks()
returns table (id bigint, student text, class_name text, day date, subject text, created_at timestamptz, answer text, answered_at timestamptz)
language sql stable security definer set search_path = public as $$
  select a.id, s.full_name, c.name, a.day, a.subject, a.created_at, a.answer, a.answered_at
    from public.grade_asks a
    join public.students s on s.id = a.student_id
    left join public.classes c on c.id = s.class_id
   where a.teacher_id = auth.uid() and (a.answered_at is null or a.answered_at > now() - interval '7 days')
   order by a.answered_at is not null, a.created_at desc
$$;
revoke all on function public.teacher_asks() from public, anon;
grant execute on function public.teacher_asks() to authenticated;

-- O'qituvchi javob beradi — ota-onaga bildirishnoma
create or replace function public.teacher_answer(p_id bigint, p_text text) returns void
language plpgsql security definer set search_path = public as $$
declare a public.grade_asks; nm text;
begin
  if length(btrim(coalesce(p_text, ''))) < 2 then raise exception 'Javobni yozing'; end if;
  update public.grade_asks set answer = left(btrim(p_text), 500), answered_at = now()
   where id = p_id and teacher_id = auth.uid() returning * into a;
  if a.id is null then raise exception 'Savol topilmadi' using errcode = '42501'; end if;
  select array_to_string((regexp_split_to_array(btrim(s.full_name), '\s+'))[1:2], ' ') into nm from public.students s where s.id = a.student_id;
  insert into public.push_queue (user_id, kind, student_id, title, body)
  select a.parent, 'javob', a.id::text, '💬 O''qituvchi javob berdi',
         nm || ' (' || coalesce(a.subject, 'dars') || ', ' || to_char(a.day, 'DD.MM') || '): ' || left(btrim(p_text), 160)
   where exists (select 1 from public.push_subs x where x.user_id = a.parent)
  on conflict do nothing;
end $$;
revoke all on function public.teacher_answer(bigint, text) from public, anon;
grant execute on function public.teacher_answer(bigint, text) to authenticated;

