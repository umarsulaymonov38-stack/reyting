-- 5. Turniket: davomat (24-qoidalar) + SMS (27, agar o'rnatilgan bo'lsa) + push
create or replace function public.tk_push(p_token text, p_events jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare e record; sid public.students.id%type; cid bigint; eid bigint; lt timestamp; n int := 0; kind text;
        has_sms boolean := to_regclass('public.sms_config') is not null;
        kf time := coalesce((select ketdi_from from public.push_config where id = 1), time '16:45');
        sf time;
begin
  if not exists (select 1 from public.tk_config where token = p_token) then
    raise exception 'Kalit noto''g''ri' using errcode = '28000';
  end if;
  if has_sms then execute 'select ketdi_from from public.sms_config where id = 1' into sf; end if;
  for e in select * from jsonb_to_recordset(p_events) as x(emp text, ts timestamptz, door text) loop
    continue when coalesce(e.emp, '') = '' or e.ts is null;
    select s.id, s.class_id into sid, cid from public.students s join public.classes c on c.id = s.class_id
     where s.ext_id = e.emp and c.kind is distinct from 'rep' and coalesce(c.grp, '') = '' limit 1;
    insert into public.turnstile_events (emp_no, student_id, ts, door)
    values (e.emp, sid::text, e.ts, coalesce(e.door, '')) on conflict do nothing returning id into eid;
    if eid is not null and sid is not null and public.yk_tk_class(cid) then
      lt := e.ts at time zone 'Asia/Tashkent';
      if lt::time <= time '09:30' then
        insert into public.daily_scores (student_id, day, att, excused, arrived_at) values (sid, lt::date, 1, false, e.ts)
        on conflict (student_id, day) do update
          set att = 1, excused = false, arrived_at = least(coalesce(public.daily_scores.arrived_at, excluded.arrived_at), excluded.arrived_at);
        n := n + 1;
      elsif lt::time >= time '16:40' then
        insert into public.daily_scores (student_id, day, left_at) values (sid, lt::date, e.ts)
        on conflict (student_id, day) do update
          set left_at = greatest(coalesce(public.daily_scores.left_at, excluded.left_at), excluded.left_at);
        n := n + 1;
      end if;
      -- xabarlar faqat yangi o'tishlar uchun (ko'prik eski kunlarni keyin yuborsa — xabar ketmaydi)
      if e.ts > now() - interval '3 hours' then
        kind := case when lt::time < kf then 'keldi' else 'ketdi' end;
        perform public.yk_push_add(kind, sid::text, e.ts);
        if has_sms then
          perform public.yk_sms_add(case when lt::time < coalesce(sf, kf) then 'keldi' else 'ketdi' end, sid::text, e.ts);
        end if;
      end if;
    end if;
    sid := null; cid := null; eid := null;
  end loop;
  return n;
end $$;
revoke all on function public.tk_push(text, jsonb) from public;
grant execute on function public.tk_push(text, jsonb) to anon, authenticated;

-- 6. Server funksiyasi uchun (faqat service_role)
create or replace function public.push_keys_get() returns public.push_secret language sql security definer set search_path = public as $$
  select * from public.push_secret where id = 1
$$;
create or replace function public.push_keys_set(p_pub text, p_priv text) returns void language sql security definer set search_path = public as $$
  insert into public.push_secret (id, public_key, private_key) values (1, p_pub, p_priv)
  on conflict (id) do nothing
$$;
create or replace function public.push_claim(p_limit int default 200) returns jsonb
language plpgsql security definer set search_path = public as $$
declare t date := (now() at time zone 'Asia/Tashkent')::date; r jsonb;
begin
  update public.push_queue set status = 'xato', error = 'eskirgan'
   where status in ('navbat', 'yuborilmoqda') and kind in ('keldi', 'ketdi') and day < t;
  with q as (
    update public.push_queue q set status = 'yuborilmoqda', tries = q.tries + 1, claimed_at = now()
     where q.id in (select x.id from public.push_queue x
                     where (x.status = 'navbat' or (x.status = 'yuborilmoqda' and x.claimed_at < now() - interval '10 minutes'))
                       and x.tries < 3
                     order by x.id limit p_limit for update skip locked)
    returning q.*)
  select coalesce(jsonb_agg(jsonb_build_object('id', q.id, 'title', q.title, 'body', q.body, 'tag', q.kind || '-' || coalesce(q.student_id, ''),
           'subs', (select coalesce(jsonb_agg(jsonb_build_object('endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth)), '[]'::jsonb)
                      from public.push_subs s where s.user_id = q.user_id))), '[]'::jsonb)
    into r from q;
  return r;
end $$;
create or replace function public.push_done(p_id bigint, p_ok boolean, p_error text) returns void
language sql security definer set search_path = public as $$
  update public.push_queue set status = case when p_ok then 'yuborildi' when tries >= 3 then 'xato' else 'navbat' end,
         sent_at = case when p_ok then now() end, error = p_error where id = p_id
$$;
create or replace function public.push_sub_del(p_endpoint text) returns void language sql security definer set search_path = public as $$
  delete from public.push_subs where endpoint = p_endpoint
$$;
revoke all on function public.push_keys_get() from public, anon, authenticated;
revoke all on function public.push_keys_set(text, text) from public, anon, authenticated;
revoke all on function public.push_claim(int) from public, anon, authenticated;
revoke all on function public.push_done(bigint, boolean, text) from public, anon, authenticated;
revoke all on function public.push_sub_del(text) from public, anon, authenticated;
grant execute on function public.push_keys_get() to service_role;
grant execute on function public.push_keys_set(text, text) to service_role;
grant execute on function public.push_claim(int) to service_role;
grant execute on function public.push_done(bigint, boolean, text) to service_role;
grant execute on function public.push_sub_del(text) to service_role;

-- 7. Har daqiqada navbatni yuborish
create or replace function public.yk_push_kick() returns void
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from public.push_queue where status = 'navbat') then
    perform net.http_post(url := 'https://yzaxyjypswpjcebmjsnj.supabase.co/functions/v1/push-yubor',
      body := '{}'::jsonb, headers := '{"Content-Type": "application/json"}'::jsonb, timeout_milliseconds := 60000);
  end if;
end $$;
revoke all on function public.yk_push_kick() from public, anon, authenticated;
select cron.schedule('yk-push-yubor', '* * * * *', 'select public.yk_push_kick()');

