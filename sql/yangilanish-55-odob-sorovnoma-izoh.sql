-- «Baho to'liq qo'yildi» (o'qituvchilar reytingi) + 1–10-sinflarda sport yo'q, yaxshilik — ota-ona javobidan
create or replace function public.yk_mark_done() returns trigger
language plpgsql security definer set search_path = public as $$
declare g text; cid bigint; done boolean; j jsonb := to_jsonb(new);
begin
  new.updated_at := now();
  if tg_table_name = 'rep_daily' then
    done := new.att is not null and (new.att = 0 or j ->> 'task' is not null);
  else
    select c.grp, c.id into g, cid from public.students s join public.classes c on c.id = s.class_id where s.id = new.student_id;
    if coalesce(g, '') <> '' then
      done := new.att is not null and (new.att = 0 or (new.hw is not null and new.activity is not null and new.behavior is not null));
    elsif public.yk_g2(cid) and new.day >= date '2026-11-09' then
      new.sport := null;
      new.kindness := case when new.att = 1 then
        (select pw.score from public.parent_week pw where pw.student_id = new.student_id and pw.week = date_trunc('week', new.day)::date) end;
      done := new.att is not null and (new.att = 0 or (new.behavior is not null and (new.book is not null or coalesce(public.yk_g1(cid), false))));
    else
      done := new.att is not null and (new.att = 0 or (new.sport is not null and new.behavior is not null and new.kindness is not null
              and (new.book is not null or coalesce(public.yk_g1(cid), false))));
    end if;
  end if;
  if not done then new.done_at := null;
  elsif new.done_at is null then new.done_at := now();
  end if;
  return new;
end $$;

-- Shu haftadagi 1–10-sinf yozuvlari yangi qoidaga o'tkaziladi (sport va o'qituvchi qo'ygan yaxshilik olib tashlanadi)
update public.daily_scores d set updated_at = now()
  from public.students s
 where s.id = d.student_id and d.day >= date '2026-11-09' and public.yk_g2(s.class_id)
   and (d.sport is not null or d.kindness is not null);

-- Ota-ona: so'rovnoma holati (faol farzand uchun)
create or replace function public.parent_week_status() returns jsonb
language sql stable security definer set search_path = public as $$
  with k as (select s.id, s.full_name, s.class_id from public.profiles p join public.students s on s.id = p.student_id
              where p.id = auth.uid() and public.yk_role() = 'parent'),
       t as (select (now() at time zone 'Asia/Tashkent')::date d)
  select jsonb_build_object(
           'ok', public.yk_g2(k.class_id),
           'open', extract(isodow from t.d) >= 5,
           'week', date_trunc('week', t.d)::date,
           'sid', k.id::text, 'name', k.full_name,
           'ans', (select jsonb_build_object('mood', pw.mood, 'note', pw.note, 'at', pw.created_at)
                     from public.parent_week pw where pw.student_id = k.id and pw.week = date_trunc('week', t.d)::date))
    from k, t
$$;
revoke all on function public.parent_week_status() from public, anon;
grant execute on function public.parent_week_status() to authenticated;

-- Ota-ona javob beradi (juma, shanba, yakshanba; haftasiga bir marta; «vijdonan» tasdig'i bilan)
create or replace function public.parent_week_submit(p_sid text, p_mood int, p_note text, p_honest boolean) returns void
language plpgsql security definer set search_path = public as $$
declare d date := (now() at time zone 'Asia/Tashkent')::date; w date := date_trunc('week', d)::date; sid public.students.id%type; cid bigint;
begin
  if public.yk_role() is distinct from 'parent' then raise exception 'Faqat ota-ona' using errcode = '42501'; end if;
  if not public.yk_is_my_kid(p_sid) then raise exception 'Bu sizning farzandingiz emas' using errcode = '42501'; end if;
  if extract(isodow from d) < 5 then raise exception 'So''rovnoma juma kuni ochiladi'; end if;
  if p_mood not between 0 and 2 then raise exception 'Javobni tanlang'; end if;
  if p_honest is not true then raise exception 'Vijdonan belgilaganingizni tasdiqlang'; end if;
  select s.id, s.class_id into sid, cid from public.students s where s.id::text = p_sid;
  if sid is null or not public.yk_g2(cid) then raise exception 'So''rovnoma faqat asosiy sinflar (1–10) uchun'; end if;
  insert into public.parent_week (student_id, week, mood, score, note, honest)
  values (sid, w, p_mood, case p_mood when 2 then 10 when 1 then 5 else 0 end, nullif(btrim(left(p_note, 500)), ''), true)
  on conflict do nothing;
  if not found then raise exception 'Bu hafta uchun javob allaqachon berilgan'; end if;
  -- haftaning kelgan kunlariga yoziladi (trigger javobdan oladi)
  update public.daily_scores set updated_at = now() where student_id = sid and day between w and w + 6;
end $$;
revoke all on function public.parent_week_submit(text, int, text, boolean) from public, anon;
grant execute on function public.parent_week_submit(text, int, text, boolean) to authenticated;

