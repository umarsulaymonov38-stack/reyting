create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  student_id text,
  student_name text,
  class_id bigint,
  parent_name text,          -- "ismim ko'rsatilmasin" belgilansa bo'sh qoladi
  phone text,
  category text not null default 'Umumiy',
  body text not null check (char_length(body) between 3 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists feedback_time_idx on public.feedback (created_at desc);
create index if not exists feedback_user_idx on public.feedback (user_id, created_at desc);

alter table public.feedback enable row level security;
grant select, insert, delete on public.feedback to authenticated;
grant usage, select on sequence public.feedback_id_seq to authenticated;

-- Ota-ona: faqat o'z nomidan yozadi (kuniga ko'pi bilan 5 ta) va faqat o'z yozganlarini ko'radi; admin hammasini ko'radi va o'chira oladi
drop policy if exists feedback_add on public.feedback;
create policy feedback_add on public.feedback for insert to authenticated
  with check (user_id = auth.uid() and public.yk_role() = 'parent'
              and (select count(*) from public.feedback f where f.user_id = auth.uid() and f.created_at > now() - interval '1 day') < 5);
drop policy if exists feedback_read on public.feedback;
create policy feedback_read on public.feedback for select to authenticated
  using (user_id = auth.uid() or public.yk_role() = 'admin');
drop policy if exists feedback_del on public.feedback;
create policy feedback_del on public.feedback for delete to authenticated
  using (public.yk_role() = 'admin');

notify pgrst, 'reload schema';
