-- ============ Fan baholarini o'zgartirish — izoh bilan ============
create or replace function public.yk_ss_reason() returns trigger
language plpgsql security definer set search_path = public as $$
declare f text; o text; n text; r text := nullif(btrim(coalesce(current_setting('yk.reason', true), '')), '');
begin
  foreach f in array array['hw', 'activity', 'grade'] loop
    o := to_jsonb(old) ->> f; n := to_jsonb(new) ->> f;
    if o is not null and n is distinct from o then
      if r is null then
        raise exception 'IZOH: qo''yilgan bahoni o''zgartirish uchun sababini yozing' using errcode = 'P0001';
      end if;
      insert into public.grade_changes (student_id, day, subject, field, old_val, new_val, reason, teacher_id)
      values (new.student_id, new.day, new.subject, f, o::int, n::int, r, auth.uid());
    end if;
  end loop;
  return new;
end $$;
drop trigger if exists yk_ss_reason on public.subject_scores;
create trigger yk_ss_reason before update on public.subject_scores for each row execute function public.yk_ss_reason();

-- O'qituvchi bahoni izoh bilan o'zgartiradi (o'z bahosini)
create or replace function public.ss_change(p_sid text, p_day date, p_field text, p_val int, p_reason text) returns void
language plpgsql set search_path = public as $$
begin
  if p_field not in ('hw', 'activity', 'grade') then raise exception 'Noto''g''ri ustun'; end if;
  if length(btrim(coalesce(p_reason, ''))) < 3 then raise exception 'IZOH: sababini yozing'; end if;
  perform set_config('yk.reason', left(btrim(p_reason), 300), true);
  execute format('update public.subject_scores set %I = $1 where student_id::text = $2 and day = $3 and teacher_id = auth.uid()', p_field)
    using p_val, p_sid, p_day;
  if not found then raise exception 'Baho topilmadi'; end if;
  perform set_config('yk.reason', '', true);
end $$;
revoke all on function public.ss_change(text, date, text, int, text) from public, anon;
grant execute on function public.ss_change(text, date, text, int, text) to authenticated;

-- Ota-ona: farzandining fan baholaridagi o'zgarishlar
create or replace function public.parent_grade_changes(p_from date, p_to date)
returns table (student_id text, day date, subject text, field text, old_val int, new_val int, reason text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select g.student_id::text, g.day, coalesce(nullif(g.subject, ''), p.full_name, 'Fan'), g.field, g.old_val, g.new_val, g.reason, g.created_at
    from public.grade_changes g
    join public.my_kids() k on k.id = g.student_id
    left join public.profiles p on p.id = g.teacher_id
   where g.day between p_from and p_to
   order by g.created_at desc
$$;
revoke all on function public.parent_grade_changes(date, date) from public, anon;
grant execute on function public.parent_grade_changes(date, date) to authenticated;

-- ============ Kunlik baho bildirishnomalari (qayta yoqiladi) ============
create or replace function public.yk_push_daily() returns trigger
language plpgsql security definer set search_path = public as $$
declare g boolean; g2 boolean; sid text := new.student_id::text; c record;
begin
  if new.day <> (now() at time zone 'Asia/Tashkent')::date then return new; end if;
  select coalesce(cl.grp, '') <> '', public.yk_g2(cl.id) into g, g2
    from public.students s join public.classes cl on cl.id = s.class_id where s.id = new.student_id;
  g := coalesce(g, false); g2 := coalesce(g2, false);
  for c in select * from (values ('book', 'Kitob o''qish', 10), ('sport', 'Sport', 10), ('behavior', case when g then 'Tartib-intizom' else 'Odoblar' end, case when g then 5 else 10 end),
                                 ('kindness', 'Ota-onaga yaxshilik', 10), ('hw', 'Uyga vazifa', 5), ('activity', 'Sinfdagi faollik', 5)) v(k, t, m) loop
    continue when (case when g then c.k not in ('hw', 'activity', 'behavior')
                        when g2 then c.k not in ('book', 'behavior')   -- 1–10-sinflar: sport yo'q, yaxshilikni ota-onaning o'zi belgilaydi
                        else c.k not in ('book', 'sport', 'behavior', 'kindness') end);
    if tg_op = 'INSERT' or (to_jsonb(new) ->> c.k) is distinct from (to_jsonb(old) ->> c.k) then
      perform public.yk_grade_mark(sid, 'd:' || c.k, (to_jsonb(new) ->> c.k)::numeric,
                                   case when c.m = 5 then 2 else 4 end, case when c.m = 5 then 5 else 9 end,
                                   c.t || ' ' || (to_jsonb(new) ->> c.k) || '/' || c.m);
    end if;
  end loop;
  if g and (tg_op = 'INSERT' or (to_jsonb(new) ->> 'beh_band') is distinct from (to_jsonb(old) ->> 'beh_band')) then
    perform public.yk_grade_note(sid, 'yomon', 'd:band', case (to_jsonb(new) ->> 'beh_band')
      when '1' then 'tartib qoidaga amal qilmadi' when '2' then 'atrofdagilar va ustozlarni hurmat qilmadi'
      when '3' then 'o''z joyini toza saqlamadi' end);
  end if;
  return new;
exception when others then
  raise warning 'push baho: %', sqlerrm;  -- bildirishnomadagi xato baho saqlanishiga to'sqinlik qilmasin
  return new;
end $$;
drop trigger if exists yk_push_daily on public.daily_scores;
create trigger yk_push_daily after insert or update on public.daily_scores for each row execute function public.yk_push_daily();

