-- shuning uchun bir nechta fan o'qituvchisi bir-birining bahosini o'chirib yubormaydi.

-- 1. O'qituvchining shu sinfdagi fani (masalan, Matematika)
alter table public.teacher_classes add column if not exists subject text;
alter table public.teacher_classes alter column role set default 'fan';
do $$ begin
  if not exists (
    select 1 from pg_index i join pg_class t on t.oid = i.indrelid
     where t.relname = 'teacher_classes' and i.indisunique
       and (select array_agg(a.attname::text order by a.attname) from pg_attribute a
             where a.attrelid = t.oid and a.attnum = any(i.indkey)) = array['class_id', 'user_id']) then
    create unique index teacher_classes_user_class_uq on public.teacher_classes (user_id, class_id);
  end if;
end $$;

-- 2. Fan baholari (o'quvchi id turi students.id bilan bir xil bo'ladi)
do $$
declare t text;
begin
  select format_type(a.atttypid, a.atttypmod) into t from pg_attribute a
   where a.attrelid = 'public.students'::regclass and a.attname = 'id';
  execute format($f$
    create table if not exists public.subject_scores (
      id bigint generated by default as identity primary key,
      student_id %s not null references public.students(id) on delete cascade,
      day date not null,
      teacher_id uuid not null default auth.uid(),
      subject text not null default '',
      att int check (att in (0, 1)),
      excused boolean not null default false,
      hw int check (hw between 0 and 5),
      activity int check (activity between 0 and 5),
      grade int check (grade between 1 and 5),
      updated_at timestamptz not null default now(),
      unique (student_id, day, teacher_id))$f$, t);
end $$;
create index if not exists subject_scores_day_idx on public.subject_scores (day);
create index if not exists subject_scores_student_idx on public.subject_scores (student_id, day);

alter table public.subject_scores enable row level security;
grant select, insert, update, delete on public.subject_scores to authenticated;
grant usage, select on sequence public.subject_scores_id_seq to authenticated;

-- Ko'radi: admin va shu sinfga biriktirilgan o'qituvchilar. Yozadi: o'qituvchi faqat o'z nomidan, faqat o'z sinfiga.
drop policy if exists ss_read on public.subject_scores;
create policy ss_read on public.subject_scores for select to authenticated using (
  public.yk_role() = 'admin'
  or exists (select 1 from public.students s join public.teacher_classes t on t.class_id = s.class_id
              where s.id = subject_scores.student_id and t.user_id = auth.uid()));
drop policy if exists ss_ins on public.subject_scores;
create policy ss_ins on public.subject_scores for insert to authenticated with check (
  teacher_id = auth.uid()
  and exists (select 1 from public.students s join public.teacher_classes t on t.class_id = s.class_id
               where s.id = subject_scores.student_id and t.user_id = auth.uid()));
drop policy if exists ss_upd on public.subject_scores;
create policy ss_upd on public.subject_scores for update to authenticated using (teacher_id = auth.uid()) with check (
  teacher_id = auth.uid()
  and exists (select 1 from public.students s join public.teacher_classes t on t.class_id = s.class_id
               where s.id = subject_scores.student_id and t.user_id = auth.uid()));
drop policy if exists ss_del on public.subject_scores;
create policy ss_del on public.subject_scores for delete to authenticated using (teacher_id = auth.uid() or public.yk_role() = 'admin');

create or replace function public.yk_ss_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists subject_scores_touch on public.subject_scores;
create trigger subject_scores_touch before update on public.subject_scores for each row execute function public.yk_ss_touch();

-- 3. Ota-ona: farzandlarining fanlar bo'yicha baholari (faqat o'z farzandlari)
create or replace function public.parent_subjects(p_from date, p_to date)
returns table (student_id text, day date, subject text, att int, excused boolean, hw int, activity int, grade int)
language sql stable security definer set search_path = public as $$
  select ss.student_id::text, ss.day, coalesce(nullif(ss.subject, ''), p.full_name, 'Fan'),
         ss.att, ss.excused, ss.hw, ss.activity, ss.grade
    from public.subject_scores ss
    join public.my_kids() k on k.id = ss.student_id
    left join public.profiles p on p.id = ss.teacher_id
   where ss.day between p_from and p_to
   order by ss.day desc, 3
$$;
revoke all on function public.parent_subjects(date, date) from public, anon;
grant execute on function public.parent_subjects(date, date) to authenticated;

notify pgrst, 'reload schema';
