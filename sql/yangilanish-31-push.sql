create extension if not exists pg_net;
create extension if not exists pg_cron;

-- 1. Sozlama (admin o'chirib-yoqishi mumkin; boshida yoqilgan)
create table if not exists public.push_config (
  id int primary key default 1 check (id = 1),
  on_keldi boolean not null default true,
  on_ketdi boolean not null default true,
  ketdi_from time not null default '16:45'
);
insert into public.push_config (id) values (1) on conflict (id) do nothing;
alter table public.push_config enable row level security;
grant select, update on public.push_config to authenticated;
drop policy if exists push_config_read on public.push_config;
create policy push_config_read on public.push_config for select to authenticated using (true);
drop policy if exists push_config_admin on public.push_config;
create policy push_config_admin on public.push_config for update to authenticated
  using (public.yk_role() = 'admin') with check (public.yk_role() = 'admin');

-- 2. VAPID kalitlari (faqat server funksiyasi; ochiq kalitni hamma o'qiy oladi)
create table if not exists public.push_secret (id int primary key default 1 check (id = 1), public_key text, private_key text);
alter table public.push_secret enable row level security;
revoke all on public.push_secret from anon, authenticated;
create or replace function public.push_public_key() returns text language sql stable security definer set search_path = public as $$
  select public_key from public.push_secret where id = 1
$$;
grant execute on function public.push_public_key() to anon, authenticated;

-- 3. Ota-onaning qurilmalari (har bir telefon/brauzer — alohida obuna)
create table if not exists public.push_subs (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  ua text,
  created_at timestamptz not null default now()
);
create index if not exists push_subs_user_idx on public.push_subs (user_id);
alter table public.push_subs enable row level security;
grant select, insert, update, delete on public.push_subs to authenticated;
grant usage, select on sequence public.push_subs_id_seq to authenticated;
drop policy if exists push_subs_own on public.push_subs;
create policy push_subs_own on public.push_subs for all to authenticated
  using (user_id = auth.uid() or public.yk_role() = 'admin') with check (user_id = auth.uid());

-- 4. Xabarlar navbati (kuniga bitta "keldi" va bitta "ketdi")
create table if not exists public.push_queue (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  kind text not null check (kind in ('keldi', 'ketdi', 'test')),
  student_id text,
  title text not null,
  body text not null,
  day date not null default (now() at time zone 'Asia/Tashkent')::date,
  status text not null default 'navbat' check (status in ('navbat', 'yuborilmoqda', 'yuborildi', 'xato')),
  tries int not null default 0,
  error text,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  unique (user_id, kind, student_id, day)
);
create index if not exists push_queue_status_idx on public.push_queue (status, id);
alter table public.push_queue enable row level security;
grant select on public.push_queue to authenticated;
drop policy if exists push_queue_read on public.push_queue;
create policy push_queue_read on public.push_queue for select to authenticated
  using (user_id = auth.uid() or public.yk_role() = 'admin');

-- Farzand turniketdan o'tganda — unga ulangan ota-onalarga xabar navbatga qo'yiladi
create or replace function public.yk_push_add(p_kind text, p_sid text, p_ts timestamptz) returns void
language plpgsql security definer set search_path = public as $$
declare c public.push_config; nm text; tm text := to_char(p_ts at time zone 'Asia/Tashkent', 'HH24:MI');
begin
  select * into c from public.push_config where id = 1;
  if c.id is null or not (case p_kind when 'keldi' then c.on_keldi when 'ketdi' then c.on_ketdi else false end) then return; end if;
  select array_to_string((regexp_split_to_array(btrim(s.full_name), '\s+'))[1:2], ' ') into nm from public.students s where s.id::text = p_sid;
  insert into public.push_queue (user_id, kind, student_id, title, body, day)
  select u.uid, p_kind, p_sid,
         case p_kind when 'keldi' then '✅ Maktabga keldi' else '🏠 Maktabdan chiqdi' end,
         nm || case p_kind when 'keldi' then ' bugun soat ' || tm || ' da maktabga keldi.' else ' soat ' || tm || ' da maktabdan chiqdi.' end,
         (p_ts at time zone 'Asia/Tashkent')::date
    from (select sp.claimed_by uid from public.student_private sp where sp.student_id::text = p_sid and sp.claimed_by is not null
          union select p.id from public.profiles p where p.role = 'parent' and p.student_id::text = p_sid) u
   where exists (select 1 from public.push_subs x where x.user_id = u.uid)
  on conflict (user_id, kind, student_id, day) do nothing;
end $$;
revoke all on function public.yk_push_add(text, text, timestamptz) from public, anon, authenticated;

